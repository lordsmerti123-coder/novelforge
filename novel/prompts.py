def state_block(state: dict[str, Any]) -> str:
    """Текущее состояние мира.

    @param state: словарь состояния партии.
    @returns: текстовый блок либо пустая строка.
    """
    if not state:
        return ""
    lines = ["Текущее состояние:"]
    for key, value in sorted(state.items()):
        rendered = json.dumps(value, ensure_ascii=False) if isinstance(value, (dict, list)) else str(value)
        lines.append(f"- {key}: {rendered}")
    return "\n".join(lines)


def interject_block(text: str, solo: bool = False) -> str:
    """Врезка пользователя: указание, которое обязано подействовать на этот ход.

    @param text: текст врезки.
    @param solo: врезка без реплики игрока — игрок не действует, а только
        направляет сцену. Без этого ведущий ждал бы действия, которого нет.
    @returns: текстовый блок либо пустая строка.
    """
    if not text.strip():
        return ""
    if solo:
        head = (
            "Игрок не действует — он только направляет сцену. Опиши, что происходит, "
            "и остановись там, где нужно его решение.\n"
        )
    else:
        head = ""
    return (
        head
        + "Указание ведущему на этот ход (выполни, не обсуждая):\n"
        + text.strip()
    )


def transcript(messages: list[Message]) -> str:
    """Стенограмма участка переписки — материал для суммаризации.

    @param messages: сообщения в хронологическом порядке.
    @returns: текст стенограммы.
    """
    lines: list[str] = []
    for message in messages:
        speaker = "Игрок" if message.role == "user" else "Ведущий"
        lines.append(f"{speaker}: {message.content.strip()}")
    return "\n\n".join(lines)



def list_presets() -> list[dict[str, Any]]:
    """Краткие описания пресетов для интерфейса."""
    return [
        {
            "key": preset["key"],
            "title": preset["title"],
            "genre": preset["genre"],
            "tone": preset["tone"],
            "brief": preset["brief"],
            # Тип и настройки кадров идут в список: без них в выпадающем
            # списке не отличить историю от переписки — они выглядят одинаково.
            "format": preset.get("format") or "story",
            "image_policy": preset.get("image_policy") or "",
            "image_frame": preset.get("image_frame") or "",
            "rules": len(preset["rules"]),
            "characters": len(preset["characters"]),
        }
        for preset in WORLD_PRESETS
    ]


def get_preset(key: str) -> dict[str, Any] | None:
    """Пресет по ключу."""
    for preset in WORLD_PRESETS:
        if preset["key"] == key:
            return preset
    return None

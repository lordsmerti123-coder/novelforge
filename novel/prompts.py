"""Сборка блоков промпта.

Каждый блок — отдельная функция, возвращающая готовый текст. Сборкой в слои и
подсчётом токенов занимается :mod:`novel.context`; здесь только текст.

Порядок блоков в итоговом промпте не случаен: сначала идёт то, что не меняется
между ходами (формат, мир, правила, персонажи, стиль), потом память и только
потом дословное окно. Такой порядок позволяет движку кэшировать префикс и не
пересчитывать неизменную часть на каждом ходу.
"""

from __future__ import annotations

import json
import re
from typing import Any

from novel.db import Character, Memory, Message, Rule, World
from novel.formats import DialogueFormat


def render(template: str, **values: str) -> str:
    """Подставляет значения в шаблон простой заменой.

    ``str.format`` здесь не годится: в промптах есть примеры JSON с фигурными
    скобками, и они были бы приняты за поля подстановки.

    @param template: текст с метками вида ``{имя}``.
    @param values: значения по именам меток.
    @returns: готовый текст.
    """
    result = template
    for key, value in values.items():
        result = result.replace("{" + key + "}", value)
    return result


def protocol_block(
    fmt: DialogueFormat, scene_policy: str = "minimal", portrait: bool = False
) -> str:
    """Описывает формат ответа: какие блоки модель обязана вернуть.

    @param fmt: тип повествования.
    @param scene_policy: когда рисовать кадры. При «никогда» блока сцены в
        ответе не спрашивают вовсе — иначе ведущий опишет кадр, нарисует его
        оркестратор, и выключенные картинки всё равно появятся.
    @param portrait: показывать собеседника крупным планом, а не сцену целиком.
    @returns: текст инструкции про теги.
    """
    lines = [
        "Формат ответа.",
        "",
        "<prose>",
        "Текст для игрока.",
        "</prose>",
    ]
    if fmt.wants_scene and scene_policy != "never":
        # Рамку задаёт настройка «что в кадре», а что именно в ней — решает
        # ведущий по ситуации: поза, ракурс, кто попал в кадр и что видно.
        if portrait:
            purpose = ("Рамка задана настройкой: кадр снят с глаз игрока, и в нём "
                       "то, что игрок видит перед собой. А вот что именно он видит "
                       "— поза, ракурс, лицо, руки, что попало в поле зрения — "
                       "решаешь ты по тому, что происходит сейчас.")
        elif fmt.scene_role == "photo":
            purpose = ("Рамка задана настройкой: это фотография, которую "
                       "собеседник отправляет игроку. Что на ней — решаешь ты: "
                       "он сам, то, что перед ним, или то, чем он занят.")
        else:
            purpose = ("Рамка задана настройкой: общий план сцены. Кого и что "
                       "показать — решаешь ты по тому, что происходит сейчас.")
        lines += [
            "<scene>",
            "{",
            '  "location": "короткое имя места",',
            '  "npc": ["кто в кадре"],',
            '  "image_prompt": "описание кадра по-английски, без имён собственных",',
            '  "style": "стиль изображения",',
            '  "sudden": false',
            "}",
            "</scene>",
            f"Назначение блока scene: {purpose}",
        ]
        # Что говорить про частоту блоков сцены, зависит от политики картинок.
        # Иначе промпт и настройка противоречат друг другу: политика «каждый ход»
        # ждёт сцену, а промпт велит не ставить её на знакомом месте — и кадра
        # нет вовсе.
        if portrait:
            lines += [
                "В поле npc укажи РОВНО ОДНОГО — того, с кем сейчас говорит игрок. "
                "В поле image_prompt опиши его ПО-АНГЛИЙСКИ так, как его видит игрок: "
                'начни словами "first person view", далее поза и то, что видно — '
                "протянутая рука, наклонённое лицо, поворот вполоборота. Кадр "
                "показывает собеседника, а не игрока: самого игрока в кадре нет.",
                "Обстановку упоминай вскользь — она нужна лишь как фон за собеседником.",
                "Внешность бери из карточки персонажа дословно, иначе он будет "
                "меняться от кадра к кадру.",
                "Ставь блок scene при каждой смене собеседника и когда его вид "
                "заметно меняется: переоделся, ранен, сменил позу.",
            ]
        elif scene_policy in ("every_turn", "every_n"):
            lines += [
                "Ставь блок scene в КАЖДОМ ответе: когда рисовать кадр, решает "
                "оркестратор, а не ты. Описание должно отражать то, что "
                "происходит именно сейчас.",
            ]
        else:
            lines += [
                "Ставь его в трёх случаях: новое место; персонаж, которого в кадре "
                "ещё не было; резкая перемена обстановки на знакомом месте — тогда "
                'поставь "sudden": true.',
                "Не ставь его, если действие продолжается там же с теми же лицами: "
                "лишний кадр стоит читателю минуту ожидания.",
            ]
        lines += [
            # Зерно ведущий не придумывает: он повторяет круглые числа из примера,
            # и кадры выходят одинаковыми. Новое зерно берёт оркестратор.
            "Поле seed заполнять не нужно вовсе: если оно повторит прежнее, кадр "
            "всё равно нарисуется с новым зерном.",
        ]
    if fmt.wants_speculative:
        lines += [
            "<speculative>",
            "[",
            '  {"trigger": "что сделает игрок", "prompt": "английское описание кадра", "seed": 12346}',
            "]",
            "</speculative>",
            "Два-три наиболее вероятных продолжения. Игрок их не видит.",
        ]
    # Блок внешности нужен всегда, а не только когда изменения уже есть: иначе
    # ведущий о нём просто не узнаёт и никогда не сообщит о переодевании.
    # Пример заполнен по-настоящему: с заглушкой вида «Имя персонажа» модель
    # блок не присылает вовсе.
    lines += [
        "<looks>",
        '{"проводник": "в дорожном плаще, волосы собраны, на пальце деревянное кольцо"}',
        "</looks>",
        "Блок looks ОБЯЗАТЕЛЕН, если чья-то внешность изменилась: переоделся, снял "
        "доспехи, ранен, перевязан, загримирован, скрыл лицо. Перечисли тех, кто "
        "изменился, и опиши, как они выглядят теперь. Это важнее карточки "
        "персонажа и переживает сводку истории — без этого блока внешность "
        "теряется. Если внешность не менялась, блок не пиши.",
    ]
    lines += [
        "",
        "Правила:",
        "- <prose> обязателен всегда; это единственное, что видит игрок.",
        "- Не упоминай в <prose> теги, JSON и сам факт существования этих блоков.",
        "- Если блок не нужен, не пиши его вовсе.",
        "- Если игрок приложил изображение, опиши своими словами то, что на нём "
        "видно, и вплети это в ответ. Просьба описать изображение важнее запрета "
        "на описания.",
    ]
    return "\n".join(lines)


def base_instruction(
    fmt: DialogueFormat, scene_policy: str = "minimal", portrait: bool = False
) -> str:
    """Инструкция формата плюс протокол ответа.

    @param fmt: формат диалога.
    @param scene_policy: политика картинок; от неё зависит, как часто ведущий
        должен ставить блок сцены.
    @param portrait: рисовать портрет собеседника вместо сцены.
    @returns: текст инструкции.
    """
    return f"{fmt.prose_style.strip()}\n\n{protocol_block(fmt, scene_policy, portrait)}"


#: Мужские слова в промпте кадра и то, чем их заменять. Границы слов обязательны:
#: без них «man» находится внутри «woman», и женские описания превращаются в
#: призраков.
MALE_WORDS: tuple[tuple[str, str], ...] = (
    (r"\bmen\b", "ghostly silhouettes"),
    (r"\bman\b", "ghostly silhouette"),
    (r"\bmales\b", "ghostly silhouettes"),
    (r"\bmale\b", "ghostly"),
    (r"\bmasculine\b", "spectral"),
    (r"\bboys\b", "ghostly silhouettes"),
    (r"\bboy\b", "ghostly silhouette"),
    (r"\bguys\b", "ghostly silhouettes"),
    (r"\bguy\b", "ghostly silhouette"),
    (r"\bgents?\b", "ghostly silhouette"),
)
#: Родственные и служебные слова нарочно не заменяются: «his father» стало бы
#: «his hooded figure», а монах в монастырском мире — призраком. Заменяется
#: только то, что прямо означает мужчину.

#: Что дописать в конец, чтобы генератор понял замену.
SILHOUETTE_TAIL = ("male figures only as translucent ghostly silhouettes, "
                   "no faces, no body detail, semi-transparent")


def shape_males(prompt: str) -> str:
    """Заменяет мужские персонажи призрачными очертаниями.

    Нужно, когда в кадре есть откровенное, а мужскую фигуру показывать не
    хочется: генератор получает очертание вместо человека.

    Заменяются только целые слова: «woman» и «women» остаются собой, потому что
    внутри них нет отдельного слова «man».

    @param prompt: собранный промпт кадра.
    @returns: промпт с заменёнными словами и пояснением в конце.
    """
    result = prompt
    replaced = False
    for pattern, replacement in MALE_WORDS:
        result, count = re.subn(pattern, replacement, result, flags=re.IGNORECASE)
        replaced = replaced or count > 0
    if not replaced:
        return prompt
    return f"{result}, {SILHOUETTE_TAIL}"


def scene_reminder(fmt: DialogueFormat, frame: str) -> str:
    """Напоминание поставить блок сцены — последним перед историей.

    Инструкция про блок стоит в начале промпта, а ведущий повторяет то, что
    видит последним: длинная проза в окне перебивает одну строку в начале.
    Поэтому просьба повторяется прямо перед историей.

    @param fmt: тип повествования.
    @param frame: рамка из настроек: ``portrait`` или ``scene``.
    @returns: напоминание либо пустая строка.
    """
    if not fmt.wants_scene:
        return ""
    if frame == "portrait":
        what = ("кадр снят с глаз игрока: собеседник перед ним. Что именно он "
                "видит — поза, ракурс, что попало в поле зрения — решаешь ты")
    else:
        what = ("общий план сцены: и собеседник, и обстановка. Кого и что "
                "показать — решаешь ты")
    return (
        "Напоминание: в конце ответа поставь блок <scene> — иначе кадра не "
        f"будет вовсе. В нём опиши по-английски, что рисовать: {what}. "
        "Опиши именно этот момент, а не то же, что в прошлом кадре."
    )


def style_reminder(fmt: DialogueFormat, personas: list[str] | None = None) -> str:
    """Короткое напоминание о стиле — последним перед историей.

    Инструкция формата стоит в начале блока правил, а история идёт в самом конце.
    Модель повторяет то, что видит последним, и длинная проза в окне перебивает
    одну строку в начале. Напоминание у конца запроса этот перевес снимает.

    Второе, что здесь сказано, — **кто говорит**. Карточки персонажей остаются в
    начале промпта, и оттуда характер не доходит: ведущий держит формат
    переписки, но пишет общими словами, хотя персонаж задуман суровым и властным.

    @param fmt: формат диалога.
    @param personas: короткие строки о собеседниках.
    @returns: напоминание.
    """
    if fmt.ui == "chat":
        text = ("Напоминание: ты пишешь в мессенджере, а не прозу. Твой ответ "
                "выглядит так:\n"
                "Марта: Ты в Замке. За тебя заплатили.\n"
                "Марта: Не путайся под ногами, и доживёшь до конца месяца.\n"
                "Две-три таких строки, каждая начинается именем и двоеточием. "
                "Абзацев, описаний обстановки, ощущений и того, что игрок "
                "чувствует, не бывает. Если выше в истории длинные абзацы — это "
                "переписка до смены формата, продолжать так не нужно.")
    else:
        text = ("Напоминание: живая проза от второго лица, 2-4 абзаца. Каждый ход "
                "двигает историю: новая информация, действие, перемена.")

    if personas:
        text += (
            "\nГовори от лица собеседника и держи его характер — цели, манеру, "
            "отношение к игроку. Общие слова вместо характера не годятся:\n"
            + "\n".join(f"- {line}" for line in personas)
        )
    return text


def world_block(world: World) -> str:
    """Описание мира.

    @param world: мир из хранилища.
    @returns: текстовый блок либо пустая строка.
    """
    parts: list[str] = []
    if world.genre:
        parts.append(f"Жанр: {world.genre}")
    if world.tone:
        parts.append(f"Тон: {world.tone}")
    if world.narrator:
        parts.append(f"Повествование: {world.narrator}")
    if world.brief:
        parts.append(world.brief.strip())
    if not parts:
        return ""
    return "Мир: " + world.name + "\n" + "\n".join(parts)


def rules_block(rules: list[Rule]) -> str:
    """Правила мира в порядке приоритета.

    @param rules: включённые правила.
    @returns: текстовый блок либо пустая строка.
    """
    if not rules:
        return ""
    lines = ["Правила мира (выполняй неукоснительно):"]
    for index, rule in enumerate(rules, start=1):
        title = f"{rule.title}: " if rule.title else ""
        lines.append(f"{index}. {title}{rule.body.strip()}")
    return "\n".join(lines)


def characters_block(characters: list[Character]) -> str:
    """Карточки персонажей.

    Внешность идёт отдельной строкой: она нужна не столько модели, сколько
    генератору изображений, который должен рисовать одного и того же персонажа
    одинаково.

    @param characters: включённые персонажи.
    @returns: текстовый блок либо пустая строка.
    """
    if not characters:
        return ""
    lines = ["Персонажи:"]
    for character in characters:
        lines.append(f"- {character.name}" + (f" ({character.role})" if character.role else ""))
        if character.description:
            lines.append(f"  характер: {character.description.strip()}")
        if character.appearance:
            lines.append(f"  внешность: {character.appearance.strip()}")
        if character.speech:
            lines.append(f"  речь: {character.speech.strip()}")
        if character.voice.strip():
            # Образцы настоящих сообщений: по ним ведущий подстраивается под
            # манеру человека, переписку которого принёс игрок. Описание манеры
            # словами этого не даёт — модель уходит в общее.
            lines.append("  как пишет сам (образцы, подражай манере):")
            for sample in character.voice.strip().splitlines():
                if sample.strip():
                    lines.append(f"    {sample.strip()}")
    return "\n".join(lines)


def style_block(world: World, fmt: DialogueFormat) -> str:
    """Инструкция по стилю изображений.

    @param world: мир, из которого берётся стиль.
    @param fmt: формат диалога.
    @returns: текстовый блок либо пустая строка.
    """
    if not fmt.wants_scene:
        return ""
    style = world.style.strip()
    if style:
        return f"Стиль изображений: {style}. Используй его в поле style блока scene."
    return (
        "Стиль изображений не задан: выбери один и придерживайся его во всех "
        "кадрах, чтобы иллюстрации выглядели единообразно."
    )


def memory_block(memories: list[Memory]) -> str:
    """Суммаризация пройденной части истории.

    @param memories: сохранённые суммаризации.
    @returns: текстовый блок либо пустая строка.
    """
    if not memories:
        return ""
    lines = ["Что было раньше (сжатое изложение):"]
    for memory in memories:
        lines.append(memory.summary.strip())
    return "\n".join(lines)


def places_block(names: list[str]) -> str:
    """Список уже известных мест мира.

    Слой нужен ради одного: чтобы ведущий называл места теми же словами. Иначе
    «замок» в одном ходу и «цитадель» в другом — это два разных места, и кадр
    каждый раз рисуется заново, без образца.

    @param names: имена мест.
    @returns: текстовый блок либо пустая строка.
    """
    if not names:
        return ""
    return (
        "Уже известные места этого мира: "
        + ", ".join(names)
        + ". Называй их точно так же, если действие происходит там же."
    )


def notes_block(notes: list[dict[str, Any]]) -> str:
    """Задумки на потом: что игрок велел и что ведущий предположил сам.

    Врезка действует один ход, правило мира — всегда. Задумка занимает середину:
    ведущий видит её каждый ход, пока она не сбудется, и сам сообщает об этом
    номером в блоке notes. Поэтому номера показываются рядом с текстом.

    **Задумки игрока и ведущего неравны.** Первые — приказ: их выполняют, когда
    дойдёт очередь. Вторые — предположение о том, куда может пойти история; если
    игрок свернул в сторону, их отбрасывают, а не подгоняют рассказ. Без этой
    разницы ведущий начинает тащить историю по своим рельсам.

    @param notes: записи с полями ``id``, ``text``, ``source`` и ``age``.
    @returns: текстовый блок либо пустая строка.
    """
    if not notes:
        return ""
    mine = [item for item in notes if item.get("source") != "model"]
    theirs = [item for item in notes if item.get("source") == "model"]
    lines: list[str] = []

    if mine:
        lines.append("Задумано игроком на потом — это должно случиться, но не "
                     "обязательно сейчас. Выполняй, когда дойдёт очередь:")
        for item in mine:
            age = item.get("age") or 0
            mark = f" (задумано {age} ходов назад)" if age > 1 else ""
            lines.append(f"{item['id']}. {str(item['text']).strip()}{mark}")

    if theirs:
        if lines:
            lines.append("")
        lines.append("Твои собственные предположения о том, куда может пойти "
                     "история. Это НЕ приказ: если игрок свернул в сторону, "
                     "отбрось их, а не подгоняй рассказ под них:")
        for item in theirs:
            horizon = item.get("horizon") or 0
            age = item.get("age") or 0
            tail = []
            if horizon:
                tail.append(f"на {horizon} ходов")
            if age:
                tail.append(f"прошло {age}")
            suffix = f" ({', '.join(tail)})" if tail else ""
            lines.append(f"{item['id']}. {str(item['text']).strip()}{suffix}")

    lines.append(
        "Когда что-то из перечисленного сбудется или потеряет смысл, укажи "
        "номера отдельным блоком:\n"
        '<notes>\n{"done": [1], "dropped": [2]}\n</notes>\n'
        "«done» — сбылось, «dropped» — больше не подходит. Если ничего не "
        "изменилось, блок не добавляй вовсе."
    )
    return "\n".join(lines)


def items_block(groups: list[tuple[str, list[tuple[str, str, int]]]]) -> str:
    """Вещи: что у кого есть.

    Главное здесь — запрет распоряжаться. Без него ведущий начинает тратить
    патроны, надевать кольцо и отдавать рюкзак за игрока: он видит список и
    считает, что это разрешение действовать. Знать о вещах он обязан, а
    пользоваться ими — только по реплике игрока.

    @param groups: пары «владелец — список вещей»; вещь это ``(имя, свойства,
        количество)``.
    @returns: текстовый блок либо пустая строка.
    """
    filled = [(holder, entries) for holder, entries in groups if entries]
    if not filled:
        return ""
    lines = [
        "Вещи в игре. Ты знаешь, что они есть, и можешь описывать их вид, но НЕ "
        "распоряжаешься ими: не тратишь, не ломаешь, не отдаёшь и не пускаешь в "
        "дело за игрока. Вещь приходит в действие только тогда, когда её "
        "использует игрок своей репликой или когда она переходит к другому по "
        "ходу событий.",
    ]
    for holder, entries in filled:
        parts = []
        for name, properties, quantity in entries:
            text = name
            if quantity > 1:
                text += f" ×{quantity}"
            if properties:
                text += f" ({properties})"
            parts.append(text)
        lines.append(f"{holder}: " + "; ".join(parts))
    return "\n".join(lines)

def looks_block(entries: list[tuple[str, str]]) -> str:
    """Как персонажи выглядят сейчас.

    Нужно потому, что сводка истории сжимает подробности: «демон в рясе
    монашки» в пересказ не попадает, и после суммаризации ведущий путает, кто
    есть кто. Карточка персонажа базовую внешность помнит, но постоянна, а тут
    лежат изменения по ходу игры — они переживают любую сводку.

    @param entries: пары «имя — как выглядит теперь».
    @returns: текстовый блок либо пустая строка.
    """
    if not entries:
        return ""
    lines = [
        "Как персонажи выглядят прямо сейчас. Это важнее карточки персонажа: если "
        "здесь сказано иначе, значит внешность изменилась по ходу игры, и "
        "опираться надо на это.",
    ]
    for name, look in entries:
        lines.append(f"{name}: {look}")
    return "\n".join(lines)


def state_block(state: dict[str, Any]) -> str:
    """Текущее состояние мира.

    @param state: словарь состояния партии.
    @returns: текстовый блок либо пустая строка.
    """
    if not state:
        return ""
    lines = ["Текущее состояние:"]
    for key, value in sorted(state.items()):
        rendered = json.dumps(value, ensure_ascii=False) if isinstance(value, (dict, list)) else str(value)
        lines.append(f"- {key}: {rendered}")
    return "\n".join(lines)


def quest_block(quest: dict[str, Any], state: dict[str, Any]) -> str:
    """Рамка квеста: где игрок, что у него и что должно случиться.

    Слой держит ведущего внутри заранее написанного сюжета. Без него он ведёт
    себя как в песочнице: придумывает новые места, выдаёт предметы, которых нет,
    и повторяет уже пройденное. Здесь же лежат условия победы и поражения —
    иначе квест нечем закончить.

    Названия мест и предметов подставляются так, как их видит игрок: ведущему
    незачем знать машинные id, он пишет текст.

    @param quest: словарь квеста.
    @param state: состояние квеста.
    @returns: текстовый блок либо пустая строка.
    """
    if not quest:
        return ""

    status = str(state.get("status") or "active")
    lines: list[str] = []

    if status in ("win", "lose"):
        lines.append(
            "КВЕСТ ОКОНЧЕН: " + ("игрок победил." if status == "win" else "игрок проиграл.")
        )
        lines.append(
            "Допиши развязку и остановись. Новых событий не придумывай, "
            "блок <quest> больше не ставь."
        )
        return "\n".join(lines)

    locations = {str(x.get("id")): x for x in quest.get("locations") or []}
    items = {str(x.get("id")): x for x in quest.get("items") or []}
    stages = quest.get("stages") or []
    index = int(state.get("stage") or 0)
    stage = stages[index] if 0 <= index < len(stages) else {}

    lines.append(f"Это квест «{quest.get('title')}». Действие идёт по написанному сюжету.")

    if stage:
        lines.append(
            f"Этап {index + 1} из {len(stages)}: «{stage.get('title')}». "
            f"Цель этапа: {stage.get('goal')}"
        )
        events = [str(x) for x in stage.get("events") or []]
        if events:
            lines.append("Что должно случиться на этом этапе (по одному, не всё сразу):")
            lines.extend(f"  — {event}" for event in events)
        if stage.get("reveal"):
            lines.append(f"К концу этапа игрок должен понять: {stage['reveal']}")

    here = locations.get(str(state.get("location") or ""), {})
    if here:
        lines.append(f"Игрок сейчас: «{here.get('name')}». {here.get('what')}")
        exits = [str(x) for x in here.get("exits") or []]
        if exits:
            names = [str(locations.get(x, {}).get("name") or x) for x in exits]
            lines.append("Отсюда можно пройти: " + ", ".join(names) + ".")
        else:
            lines.append("Отсюда выхода нет.")

    carried = [items.get(str(x), {}).get("name") or x for x in state.get("carried") or []]
    lines.append(
        "У игрока в руках: " + (", ".join(str(x) for x in carried) if carried else "ничего")
        + ". Других предметов у него нет и появиться из ниоткуда они не могут."
    )

    # Что здесь можно найти. Без этого списка ведущий о предметах не знает вовсе:
    # он описывает находку в тексте, но заявить её не может, и квест стоит на
    # месте — ключ-карта лежит на ресепшене, а игрок уходит с пустыми руками.
    taken = {str(x) for x in state.get("carried") or []}
    spent = {str(x) for x in state.get("used") or []}
    here_id = str(state.get("location") or "")
    findable = [
        thing for thing in quest.get("items") or []
        if str(thing.get("where") or "") == here_id
        and str(thing.get("id")) not in taken
        and str(thing.get("id")) not in spent
    ]
    if findable:
        lines.append("Здесь можно найти (если игрок ищет — пусть находит):")
        for thing in findable:
            lines.append(f"  — {thing.get('name')}: {thing.get('opens')}")
        lines.append(
            "Найденное обязательно заяви в блоке <quest> полем take: без этого "
            "предмета у игрока не будет, и дальше он не пройдёт."
        )
    else:
        lines.append("Здесь искать нечего: всё, что было, уже взято или потрачено.")

    # Отклонённое ведущему показывается: он поправляется сам, без вмешательства
    # игрока. Без этого он повторяет одну и ту же ошибку каждый ход.
    log = [str(x) for x in state.get("log") or []]
    if log:
        lines.append("Что в прошлый раз не приняли — так больше не делай:")
        lines.extend(f"  — {entry}" for entry in log[-4:])

    lines.append(f"Победа: {quest.get('goal')}")
    lines.append(f"Поражение: {quest.get('fail')}")

    lines.append(
        "Требования к ходу:\n"
        "  — двигай историю вперёд, не повторяй уже случившееся;\n"
        "  — не выдумывай мест и предметов сверх написанного;\n"
        "  — нашёл предмет — заяви его в <quest> полем take, применил — полем use;\n"
        "  — не давай пройти туда, куда нет выхода, и не выдавай предметов, "
        "которых нет в руках;\n"
        "  — не перескакивай этапы: следующий начинается, когда цель достигнута;\n"
        "  — подсказки давай вместе с зацепкой, не заставляй угадывать наугад;\n"
        "  — не заканчивай ход вопросом «что будешь делать?» — ставь перед фактом;\n"
        "  — в конце ответа поставь блок <quest> с тем, что изменилось."
    )
    return "\n".join(lines)


def interject_block(text: str, solo: bool = False) -> str:
    """Врезка пользователя: указание, которое обязано подействовать на этот ход.

    @param text: текст врезки.
    @param solo: врезка без реплики игрока — игрок не действует, а только
        направляет сцену. Без этого ведущий ждал бы действия, которого нет.
    @returns: текстовый блок либо пустая строка.
    """
    if not text.strip():
        return ""
    if solo:
        head = (
            "Игрок не действует — он только направляет сцену. Опиши, что происходит, "
            "и остановись там, где нужно его решение.\n"
        )
    else:
        head = ""
    return (
        head
        + "Указание ведущему на этот ход (выполни, не обсуждая):\n"
        + text.strip()
    )


def transcript(messages: list[Message]) -> str:
    """Стенограмма участка переписки — материал для суммаризации.

    @param messages: сообщения в хронологическом порядке.
    @returns: текст стенограммы.
    """
    lines: list[str] = []
    for message in messages:
        speaker = "Игрок" if message.role == "user" else "Ведущий"
        lines.append(f"{speaker}: {message.content.strip()}")
    return "\n\n".join(lines)


